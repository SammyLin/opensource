// Prerenders src/index.html into static, crawlable pages for each language and
// writes sitemap.xml + robots.txt. Run: node build.js  (or: npm run build)
//
// The page's own script runs inside jsdom, so the static HTML is exactly what a
// browser would render (hero text, filters, every program card, per-language
// meta tags). The live page still fetches programs.json and re-renders on load.
const fs = require('fs');
const path = require('path');
const { JSDOM } = require('jsdom');

const SITE = 'https://opensource.3mi.ai';
const ROOT = __dirname;
const PUBLIC = path.join(ROOT, 'public');
const TEMPLATE = fs.readFileSync(path.join(ROOT, 'src', 'index.html'), 'utf-8');
const DATA_TEXT = fs.readFileSync(path.join(PUBLIC, 'data', 'programs.json'), 'utf-8');
const data = JSON.parse(DATA_TEXT);

const LANGS = [
    { lang: 'zh-Hant', path: '/' },
    { lang: 'zh-Hans', path: '/zh-hans/' },
    { lang: 'en', path: '/en/' },
];
const langPath = (lang, id) => LANGS.find(l => l.lang === lang).path + (id ? `p/${id}/` : '');
// One listing page per language, plus one page per program per language.
const PAGES = [
    ...LANGS.map(l => ({ lang: l.lang, path: l.path, out: `${l.path.slice(1)}index.html`, lastmod: null })),
    ...data.programs.flatMap(p => LANGS.map(l => ({
        lang: l.lang, id: p.id, path: langPath(l.lang, p.id), out: `${langPath(l.lang, p.id).slice(1)}index.html`, lastmod: p.lastVerified,
    }))),
];
const BANNER = '<!-- Generated by build.js from src/index.html. Edit the template, then run `npm run build`. -->';
const lastmod = data.programs.map(p => p.lastVerified).sort().at(-1);

function programLd(doc, lang, id) {
    const p = data.programs.find(x => x.id === id);
    const url = SITE + langPath(lang, id);
    const home = SITE + langPath(lang);
    return JSON.stringify({
        '@context': 'https://schema.org',
        '@graph': [
            {
                '@type': 'WebPage',
                '@id': `${url}#page`,
                url,
                name: doc.title,
                description: doc.querySelector('meta[name="description"]').content,
                inLanguage: lang,
                isPartOf: { '@id': `${SITE}/#website` },
                dateModified: p.lastVerified,
                primaryImageOfPage: doc.querySelector('meta[property="og:image"]').content,
                breadcrumb: { '@id': `${url}#breadcrumb` },
                about: { '@type': 'Thing', name: p.name, url: p.link, description: p.whyItHelps[lang] },
            },
            {
                '@type': 'BreadcrumbList',
                '@id': `${url}#breadcrumb`,
                itemListElement: [
                    { '@type': 'ListItem', position: 1, name: 'OSS Perks', item: home },
                    { '@type': 'ListItem', position: 2, name: p.name, item: url },
                ],
            },
        ],
    }, null, 2).replace(/</g, '\\u003c');
}

function jsonLd(doc, lang) {
    const url = SITE + langPath(lang);
    const desc = doc.querySelector('meta[name="description"]').content;
    const graph = {
        '@context': 'https://schema.org',
        '@graph': [
            {
                '@type': 'WebSite',
                '@id': `${SITE}/#website`,
                name: 'OSS Perks',
                alternateName: ['開源福利社', '开源福利社'],
                url: `${SITE}/`,
                inLanguage: ['zh-Hant', 'zh-Hans', 'en'],
            },
            {
                '@type': 'CollectionPage',
                '@id': `${url}#page`,
                url,
                name: doc.title,
                description: desc,
                inLanguage: lang,
                isPartOf: { '@id': `${SITE}/#website` },
                dateModified: lastmod,
                mainEntity: {
                    '@type': 'ItemList',
                    numberOfItems: data.programs.length,
                    itemListElement: data.programs.map((p, i) => ({
                        '@type': 'ListItem',
                        position: i + 1,
                        name: p.name,
                        url: SITE + langPath(lang, p.id),
                        description: (p.whyItHelps || p.whatYouGet)[lang],
                    })),
                },
            },
        ],
    };
    // Escape "<" so the JSON can never close the <script> element early.
    return JSON.stringify(graph, null, 2).replace(/</g, '\\u003c');
}

async function render({ lang, id, path: pagePath, out }) {
    const dom = new JSDOM(TEMPLATE, {
        url: SITE + pagePath,
        runScripts: 'dangerously',
        pretendToBeVisual: true,
        beforeParse(window) {
            window.fetch = async () => ({ ok: true, json: async () => JSON.parse(DATA_TEXT) });
            window.console.error = (...args) => { throw new Error(`page error (${lang}): ${args.join(' ')}`); };
        },
    });
    const { document } = dom.window;
    const ready = () => id ? document.querySelector('#detail .detail-card') : document.querySelector('#programs .card');
    for (let i = 0; i < 100 && !ready(); i++) {
        await new Promise(r => setTimeout(r, 20));
    }
    if (document.documentElement.lang !== lang) throw new Error(`${out}: <html lang> is ${document.documentElement.lang}`);
    let summary;
    if (id) {
        const name = data.programs.find(p => p.id === id).name;
        const h1 = document.querySelector('#detail h1')?.textContent;
        if (h1 !== name) throw new Error(`${out}: expected <h1>${name}</h1>, got ${h1}`);
        if (document.querySelector('#canonical').href !== SITE + pagePath) throw new Error(`${out}: wrong canonical`);
        summary = h1;
    } else {
        const cards = document.querySelectorAll('#programs .card').length;
        if (cards !== data.programs.length) throw new Error(`${out}: rendered ${cards} cards, expected ${data.programs.length}`);
        summary = `${cards} cards`;
    }

    const ld = document.createElement('script');
    ld.type = 'application/ld+json';
    ld.textContent = '\n' + (id ? programLd(document, lang, id) : jsonLd(document, lang)) + '\n    ';
    document.head.appendChild(ld);

    const html = dom.serialize().replace(/^<!DOCTYPE html>/i, `<!DOCTYPE html>\n${BANNER}`) + '\n';
    dom.window.close();
    const file = path.join(PUBLIC, out);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, html);
    return { out, summary };
}

function sitemap() {
    const alt = id => LANGS.map(l => `    <xhtml:link rel="alternate" hreflang="${l.lang}" href="${SITE}${langPath(l.lang, id)}"/>`)
        .concat(`    <xhtml:link rel="alternate" hreflang="x-default" href="${SITE}${langPath('zh-Hant', id)}"/>`).join('\n');
    const urls = PAGES.map(p => `  <url>\n    <loc>${SITE}${p.path}</loc>\n    <lastmod>${p.lastmod || lastmod}</lastmod>\n${alt(p.id)}\n  </url>`).join('\n');
    return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${urls}\n</urlset>\n`;
}

(async () => {
    for (const page of PAGES) {
        const r = await render(page);
        if (!page.id) console.log(`public/${r.out}: ${r.summary}`);
    }
    console.log(`public/**/p/<id>/index.html: ${data.programs.length} programs × ${LANGS.length} languages`);
    // Remove pages for programs that no longer exist, so old URLs 404 instead of serving stale content.
    for (const l of LANGS) {
        const dir = path.join(PUBLIC, l.path.slice(1), 'p');
        if (!fs.existsSync(dir)) continue;
        for (const name of fs.readdirSync(dir)) {
            if (!data.programs.some(p => p.id === name)) {
                fs.rmSync(path.join(dir, name), { recursive: true, force: true });
                console.log(`removed stale public/${l.path.slice(1)}p/${name}/`);
            }
        }
    }
    fs.writeFileSync(path.join(PUBLIC, 'sitemap.xml'), sitemap());
    fs.writeFileSync(path.join(PUBLIC, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${SITE}/sitemap.xml\n`);
    console.log('public/sitemap.xml, public/robots.txt');
})().catch(err => {
    console.error(err.message || err);
    process.exit(1);
});
